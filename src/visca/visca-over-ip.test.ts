import { describe, expect, test } from 'vitest'
import { encodeViscaOverIpPacket, ViscaOverIpParser } from './visca-over-ip.js'

describe('LV20N VISCA over IP packets', () => {
	test('encodes command and inquiry headers with payload length and sequence', () => {
		expect(encodeViscaOverIpPacket('command', 1, [0x81, 0x01, 0x04, 0x0a, 0x02, 0xff])).toStrictEqual([
			0x01, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x01, 0x81, 0x01, 0x04, 0x0a, 0x02, 0xff,
		])
		expect(encodeViscaOverIpPacket('inquiry', 0x02020201, [0x81, 0x09, 0x04, 0x39, 0xff])).toStrictEqual([
			0x01, 0x10, 0x00, 0x05, 0x02, 0x02, 0x02, 0x01, 0x81, 0x09, 0x04, 0x39, 0xff,
		])
	})

	test('extracts response payloads across partial and combined TCP data', () => {
		const parser = new ViscaOverIpParser()

		expect(parser.push([0x01, 0x11, 0x00])).toStrictEqual([])
		expect(parser.push([0x03, 0x00, 0x00, 0x00, 0x01, 0x90, 0x41, 0xff, 0x01, 0x11])).toStrictEqual([
			{ sequence: 1, payload: [0x90, 0x41, 0xff] },
		])
		expect(parser.push([0x00, 0x04, 0x00, 0x00, 0x00, 0x02, 0x90, 0x50, 0x0a, 0xff])).toStrictEqual([
			{ sequence: 2, payload: [0x90, 0x50, 0x0a, 0xff] },
		])
	})

	test('rejects packets that are not LV20N VISCA responses', () => {
		const parser = new ViscaOverIpParser()
		expect(() => parser.push([0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0xff])).toThrow(
			'Unexpected VISCA over IP response type',
		)
	})
})
